const fs = require("node:fs");
const path = require("node:path");

const directory = path.join(__dirname, "../lib/core/localization");
const read = (locale) => JSON.parse(fs.readFileSync(path.join(directory, `app_${locale}.arb`), "utf8"));
const en = read("en");
const ur = read("ur");
const keys = (catalog) => Object.keys(catalog).filter((key) => !key.startsWith("@")).sort();
const missing = keys(en).filter((key) => !Object.hasOwn(ur, key));
const extra = keys(ur).filter((key) => !Object.hasOwn(en, key));
if (missing.length || extra.length) throw new Error(JSON.stringify({ missing, extra }));
const placeholders = (value) => [...value.matchAll(/\{([a-zA-Z_][\w]*)\}/g)].map((match) => match[1]).sort().join(",");
const quote = (value) => JSON.stringify(value).replaceAll("$", "\\$");
const rows = keys(en).map((key) => {
  if (typeof en[key] !== "string" || typeof ur[key] !== "string" || !ur[key].trim() ||
      placeholders(en[key]) !== placeholders(ur[key])) {
    throw new Error(`Invalid translation or placeholders: ${key}`);
  }
  return `  ${quote(en[key])}: ${quote(ur[key])},`;
});
const generated = "// Generated by tool/localization_catalog.cjs.\n" +
  "const urduMessages = <String, String>{\n" + rows.join("\n") + "\n};\n";
const target = path.join(directory, "app_messages.g.dart");
if (process.argv.includes("--write")) fs.writeFileSync(target, generated);
else if (!fs.existsSync(target) || fs.readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== generated) {
  throw new Error("Run node tool/localization_catalog.cjs --write and commit the generated catalog.");
}
console.log(`${rows.length} English/Urdu messages have matching keys and placeholders.`);
